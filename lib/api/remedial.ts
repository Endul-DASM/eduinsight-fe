import { cache } from "react";
import type { AiJobAccepted } from "./ai-jobs";
import { ApiError, apiFetch, isMockMode } from "./client";
import type { BloomLevel, LearningObjectiveRef, Question } from "./types";

// Remedial module of eduinsight-be (BE-12, AI-12 – 14; SRS FR-G-100 – 107): Siswa Target, groups with their
// packages and ACC, and the AI remedial questions. Scores are 0–100 with two decimals.

export type RemedialLevel = "belum_paham" | "paham_sebagian" | "butuh_latihan";
export type RemedialStudent = { id: string; name: string; username: string; nis: string | null };

export type RemedialTarget = {
  student: RemedialStudent;
  sourceScore: number;
  status: "perlu_remedial" | "menunggu_materi" | "mengerjakan" | "reassessment" | "tuntas";
  cycle: number;
  needsFollowUp: boolean;
  groupId: string | null;
  groupLevel: RemedialLevel | null;
  finalScore: number;
};

export type WeakObjective = { learningObjective: LearningObjectiveRef; chapterNumber: number; chapterName: string; average: number };

export type SourceRemedial = {
  maxCycles: number;
  targets: RemedialTarget[];
  weakObjectives: WeakObjective[];
};

export type PackageMaterial = {
  id: string;
  title: string;
  chapterId: string | null;
  subchapterId: string | null;
  sections: { id: string; heading: string | null; sourcePage: number | null }[];
};

// materi: a material of the package; latihan: an AI practice question (AI-13), approved with the group's ACC.
export type RemedialItem =
  | { id: string; kind: "materi"; material: PackageMaterial; question: null }
  | { id: string; kind: "latihan" | "remedial_resmi"; material: null; question: Question | null };

export type RemedialGroup = {
  id: string;
  level: RemedialLevel;
  method: "kmeans" | "rule";
  approvalStatus: "pending" | "approved" | "rejected";
  approvedAt: string | null;
  reviewNote: string | null;
  // Prepared automatically after a low post-test (FR-G-048).
  autoGenerated: boolean;
  students: RemedialStudent[];
  weakObjectives: WeakObjective[];
  items: RemedialItem[];
};

export type RemedialGroups = {
  sourceAssessmentId: string;
  cycle: number;
  groups: RemedialGroup[];
  // Targets of the cycle in no group, e.g. graded after the groups were made.
  ungrouped: RemedialStudent[];
};

function path(id: string) {
  return encodeURIComponent(id);
}

// Not a remedial source (not published, or a type that has no remedial) answers 404 or 422.
async function orNull<T>(request: Promise<T>): Promise<T | null> {
  try {
    return await request;
  } catch (error) {
    if (error instanceof ApiError && [403, 404, 422].includes(error.status)) return null;
    throw error;
  }
}

// GET /assessments/:id/remedial — Siswa Target with their group (FR-G-100, FR-G-101).
export const getSourceRemedial = cache(async (sourceId: string): Promise<SourceRemedial | null> => {
  if (isMockMode) return null;
  return orNull(apiFetch<SourceRemedial>(`/assessments/${path(sourceId)}/remedial`));
});

// GET /assessments/:id/remedial/groups — the groups of the current cycle.
export const getRemedialGroups = cache(async (sourceId: string): Promise<RemedialGroups | null> => {
  if (isMockMode) return null;
  return orNull(apiFetch<RemedialGroups>(`/assessments/${path(sourceId)}/remedial/groups`));
});

// POST /assessments/:id/remedial/groups — groups the targets (K-Means, or by rule for few students) and suggests the
// materials of their weak TPs. 409 groups_approved once one is approved.
export async function generateRemedialGroups(sourceId: string): Promise<RemedialGroups> {
  return apiFetch<RemedialGroups>(`/assessments/${path(sourceId)}/remedial/groups`, { method: "POST" });
}

// PUT /remedial-groups/:id/students — students taken from another group of the cycle leave it.
export async function setGroupStudents(groupId: string, studentIds: string[]): Promise<RemedialGroups> {
  return apiFetch<RemedialGroups>(`/remedial-groups/${path(groupId)}/students`, {
    method: "PUT",
    body: JSON.stringify({ studentIds }),
  });
}

// PUT /remedial-groups/:id/items — the package's materials, in order; practice questions are kept.
export async function setGroupMaterials(groupId: string, materialIds: string[]): Promise<RemedialGroups> {
  return apiFetch<RemedialGroups>(`/remedial-groups/${path(groupId)}/items`, {
    method: "PUT",
    body: JSON.stringify({ materialIds }),
  });
}

// POST /remedial-groups/:id/approve — ACC of the package, its practice questions included (FR-G-104).
export async function approveGroup(groupId: string): Promise<RemedialGroups> {
  return apiFetch<RemedialGroups>(`/remedial-groups/${path(groupId)}/approve`, { method: "POST" });
}

export async function rejectGroup(groupId: string, note: string | null): Promise<RemedialGroups> {
  return apiFetch<RemedialGroups>(`/remedial-groups/${path(groupId)}/reject`, {
    method: "POST",
    body: JSON.stringify({ note }),
  });
}

// POST /remedial-groups/:id/practice → 202 { jobId } (AI-13, FR-G-102). Replaces the group's practice questions still
// waiting for ACC.
export async function requestPractice(groupId: string, count: number, bloomLevel: BloomLevel): Promise<AiJobAccepted> {
  return apiFetch<AiJobAccepted>(`/remedial-groups/${path(groupId)}/practice`, {
    method: "POST",
    body: JSON.stringify({ count, bloomLevel }),
  });
}

// DELETE /remedial-items/:id — one practice question, before the group's ACC.
export async function deleteRemedialItem(itemId: string): Promise<RemedialGroups> {
  return apiFetch<RemedialGroups>(`/remedial-items/${path(itemId)}`, { method: "DELETE" });
}

// POST /assessments/:id/remedial/official-draft → 202 { jobId, assessmentId } (AI-14, FR-G-103): AI questions on the
// source's weak TPs, in its draft official remedial (made if missing). Review and ACC them in that assessment.
export async function requestOfficialDraft(
  sourceId: string,
  counts: { pg: number; uraian: number },
  bloomLevel: BloomLevel,
): Promise<AiJobAccepted & { assessmentId: string }> {
  return apiFetch(`/assessments/${path(sourceId)}/remedial/official-draft`, {
    method: "POST",
    body: JSON.stringify({ counts, bloomLevel }),
  });
}
